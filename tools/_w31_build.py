def load_keys():
    raw = open(SRC, encoding="utf-8").read().splitlines()
    seg = raw[START - 1:END]
    assert len(seg) == 400, "segment length %d" % len(seg)
    keys = []
    for i, ln in enumerate(seg):
        s = ln.strip()
        if s.endswith(","):
            s = s[:-1]
        obj = json.loads("{" + s + "}")
        assert len(obj) == 1
        (k, v), = obj.items()
        assert v == "", (i, ln)
        keys.append(k)
    return keys


def main():
    keys = load_keys()
    assert len(PAIRS) == len(keys), (len(PAIRS), len(keys))

    # strict 1:1 positional alignment check
    bad = []
    for i, (anchor, _) in enumerate(PAIRS):
        if not keys[i].startswith(anchor):
            bad.append((i + START, anchor, keys[i]))
    if bad:
        print("ALIGNMENT ERRORS:")
        for b in bad:
            print("  line %d anchor=%r key=%r" % b)
        sys.exit(1)

    result = collections.OrderedDict()
    for k, (_, v) in zip(keys, PAIRS):
        result[k] = v

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(result, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print("wrote %s with %d entries" % (OUT, len(result)))


if __name__ == "__main__":
    main()
