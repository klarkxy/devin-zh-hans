    keys = list(obj.keys())
    lines = raw.splitlines()

    assert len(lines) >= LAST_LINE, "source shorter than expected"
    # the JSON file starts with a "{" line, so file line N (>=2) is keys[N-2]
    span = keys[FIRST_LINE - 2:LAST_LINE - 1]
    print("source entries in range:", len(span))
    assert len(span) == LAST_LINE - FIRST_LINE + 1 == 400, "key count mismatch"
    assert span[0] == "The link presentation provider failed to load.", span[0]
    assert span[-1] == "Trusted Folders", span[-1]
    assert len(TR) == len(span), f"translations {len(TR)} != keys {len(span)}"

    # sanity: every key appears verbatim on its source line
    for i, k in enumerate(span):
        line = lines[FIRST_LINE - 1 + i]
        head = '"' + json.dumps(k, ensure_ascii=False)[1:-1] + '":'
        assert line.startswith(head), (i, FIRST_LINE + i, line[:80])

    ph = re.compile(r"\{\d+\}")
    problems = []
    for i, (k, v) in enumerate(zip(span, TR)):
        n = FIRST_LINE + i
        if sorted(ph.findall(k)) != sorted(ph.findall(v)):
            problems.append((n, "placeholders", sorted(ph.findall(k)), sorted(ph.findall(v))))
        if '"' in v:
            problems.append((n, "ascii quote", v))
        if "\\" in v:
            problems.append((n, "backslash", v))
        if not v.strip():
            problems.append((n, "empty", k))
        if k.endswith("..."):
            if not v.endswith("……"):
                problems.append((n, "ellipsis", v))
        elif k.endswith("."):
            if not v.endswith("。"):
                problems.append((n, "period", v))
        elif not k.endswith(("?", "!")) and v.endswith("。"):
            problems.append((n, "extra period", v))

    if problems:
        for p in problems:
            print("PROBLEM:", p)
        sys.exit(1)

    out = {k: v for k, v in zip(span, TR)}
