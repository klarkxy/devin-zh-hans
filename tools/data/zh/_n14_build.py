def main():
    with io.open(SRC, encoding="utf-8-sig") as f:
        lines = f.read().splitlines()

    slice_lines = lines[FIRST_LINE - 1:LAST_LINE]
    keys = []
    for i, line in enumerate(slice_lines, start=FIRST_LINE):
        m = LINE_RE.match(line)
        if not m:
            raise SystemExit("unparsable source line %d: %r" % (i, line))
        keys.append(m.group(1))

    print("source entries: %d (lines %d-%d)" % (len(keys), FIRST_LINE, LAST_LINE))
    if len(TR) != len(keys):
        raise SystemExit("TR has %d entries, source slice has %d" % (len(TR), len(keys)))

    out_parts = []
    kept = 0
    skipped = []
    for raw_key, value in zip(keys, TR):
        key = json.loads(raw_key)
        if value is None:
            skipped.append(key)
            continue
        out_parts.append(
            "  %s: %s" % (raw_key, json.dumps(value, ensure_ascii=False))
        )
        kept += 1

    body = "{\n" + ",\n".join(out_parts) + "\n}\n"
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(body)

    print("wrote %s: %d entries, %d skipped" % (OUT, kept, len(skipped)))
    print("skipped keys:")
    for k in skipped:
        print("  - %r" % k)


if __name__ == "__main__":
    main()
