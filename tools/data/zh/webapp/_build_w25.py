KEY_RE = re.compile(r'^\s*("(?:[^"\\]|\\.)*")\s*:')


def load_source_keys():
    with open(SRC, encoding="utf-8") as f:
        raw = f.read().splitlines()
    out = []
    for ln in range(START, END + 1):
        line = raw[ln - 1]
        m = KEY_RE.match(line)
        if not m:
            raise SystemExit("unparsable source line %d: %r" % (ln, line))
        out.append((ln, json.loads(m.group(1))))
    return out


def main():
    pairs = load_source_keys()
    missing = [ln for ln, _ in pairs if ln not in T]
    extra = sorted(set(T) - {ln for ln, _ in pairs})
    if missing or extra:
        raise SystemExit("translation map mismatch: missing=%s extra=%s" % (missing, extra))

    data = {}
    for ln, key in pairs:
        data[key] = T[ln]

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print("wrote %d entries -> %s" % (len(data), OUT))


if __name__ == "__main__":
    main()
