KEY_RE = re.compile(r'^\s*("(?:[^"\\]|\\.)*")\s*:')

with open(SRC, encoding="utf-8") as f:
    raw = f.read().splitlines()

expected = set(range(START, END + 1))
got = set(T)
if expected != got:
    raise SystemExit("line coverage mismatch: missing=%r extra=%r"
                     % (sorted(expected - got), sorted(got - expected)))

pairs = []
for ln in range(START, END + 1):
    m = KEY_RE.match(raw[ln - 1])
    if not m:
        raise SystemExit("unparsable source line %d" % ln)
    pairs.append((json.loads(m.group(1)), T[ln]))

# duplicate keys cannot survive a JSON object; report before writing
keys = [k for k, _ in pairs]
assert len(keys) == len(set(keys)), "duplicate keys in range: %r" % (
    [k for k in set(keys) if keys.count(k) > 1],)

for k, v in pairs:
    if '"' in v or "\\" in v:
        raise SystemExit("forbidden char in value for %r: %r" % (k, v))
    if not v.strip():
        raise SystemExit("empty value for %r" % (k,))

