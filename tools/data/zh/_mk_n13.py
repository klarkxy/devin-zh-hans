def main():
    raw = io.open(SRC, encoding="utf-8").read().splitlines()
    keys = {}
    for n in range(START, END + 1):
        s = raw[n - 1].strip()
        if s.endswith(","):
            s = s[:-1]
        obj = json.loads("{" + s + "}")
        (k,) = obj.keys()
        keys[n] = k

    missing = [n for n in range(START, END + 1) if n not in TR]
    if missing:
        print("MISSING LINES:", missing)
        return 1
    stray = [n for n in TR if n < START or n > END]
    if stray:
        print("STRAY LINES:", stray)
        return 1

    out = {}
    skipped = []
    for n in range(START, END + 1):
        v = TR[n]
        if v is None:
            skipped.append((n, keys[n]))
            continue
        out[keys[n]] = v

    with io.open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
        f.write("\n")

    print("range:", START, "-", END, "entries:", END - START + 1)
    print("written:", len(out))
    print("skipped:", skipped)
    return 0


